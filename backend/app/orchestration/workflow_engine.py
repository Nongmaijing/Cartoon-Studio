class WorkflowError(ValueError):
    pass


def can_transition(current: str, target: str) -> bool:
    return target in TRANSITIONS.get(current, set())


def assert_transition(current: str, target: str) -> None:
    if current not in TRANSITIONS:
        raise WorkflowError(f"Unknown production state '{current}'.")
    if target not in TRANSITIONS[current]:
        raise WorkflowError(f"Illegal production transition: {current} -> {target}.")


def next_state(current: str) -> str | None:
    if current not in PRODUCTION_STAGES:
        return None
    index = PRODUCTION_STAGES.index(current)
    if index + 1 >= len(PRODUCTION_STAGES):
        return COMPLETED
    return PRODUCTION_STAGES[index + 1]


def stage_index(state: str) -> int:
    return PRODUCTION_STAGES.index(state) if state in PRODUCTION_STAGES else -1


def is_terminal(state: str) -> bool:
    return state in TERMINAL_STATES


def validate_state(state: str) -> str:
    if state not in ALL_STATES:
        raise WorkflowError(f"Unknown production state '{state}'.")
    return state
